#!/bin/sh
# Flatten the docs/ design set into one plain-text reading copy.
#
# Input is the whole document set, concatenated in reading order (README first, so its
# traceability table serves as the dump's table of contents). Each file already opens with
# its own "# Title", which is what separates the sections once the markers are stripped.
#
# Block level: fenced code blocks are KEPT, indented four spaces and passed through
#   verbatim — they carry the ASCII diagrams, the descriptor() snippet, the REPL menu and
#   the measured tables. Dropped instead: image lines, table separator rows (|---|),
#   horizontal rules, HTML anchors, and the per-file navigation blockquote that would
#   otherwise repeat nineteen times.
# Inline level (prose lines only, never code): [text](url) -> text; heading markers,
#   emphasis (*), inline-code backticks, blockquote '>', &nbsp;, and table pipes (kept as
#   spacing) are removed. Underscores are left alone.
#
# All of it runs in one awk pass on purpose: the inline rules must not touch code, and a
# sed stage would have no way to tell the two apart.
#
# Usage: extract-design-text.sh [OUT.txt]
set -e
OUT="${1:-PLEXUS_DESIGN_TEXT_ONLY.txt}"

# Reading order. Explicit, not a glob: lexicographic sort would file design.md after
# 10-implementation.md, and the appendices must trail the specification.
SET="docs/README.md
docs/design.md
docs/01-architecture.md
docs/02-core-model.md
docs/03-invariants.md
docs/04-symmetry.md
docs/05-trie.md
docs/06-search.md
docs/07-descriptors.md
docs/08-diagnostics.md
docs/09-api.md
docs/10-implementation.md
docs/appendices/A-mathematical-background.md
docs/appendices/B-design-rationale.md
docs/appendices/C-rejected-designs.md
docs/appendices/D-performance-notes.md
docs/appendices/E-formal-proofs.md
docs/appendices/F-examples.md
docs/appendices/G-history.md"

for f in $SET; do
    [ -f "$f" ] || { echo "missing: $f" >&2; exit 1; }
done

{
    echo "PLEXUS — DESIGN DOCUMENTATION (plain-text reading copy)"
    echo
    echo "Generated by scripts/extract-design-text.sh from the Markdown set under docs/."
    echo "Do not edit this file; edit the source under docs/ and the pre-commit hook will"
    echo "regenerate it. Markdown markers are stripped; code blocks are indented verbatim."
    echo
    for f in $SET; do echo; cat "$f"; done
} | awk '
    # --- link text out of [text](url), without regex backreferences -----------------
    function delink(s,   p, i, lb, rp, text) {
        while ((p = index(s, "](")) > 0) {
            lb = 0
            for (i = p; i >= 1; i--) if (substr(s, i, 1) == "[") { lb = i; break }
            if (lb == 0) break
            rp = index(substr(s, p + 2), ")")
            if (rp == 0) break
            rp = p + 1 + rp
            text = substr(s, lb + 1, p - lb - 1)
            s = substr(s, 1, lb - 1) text substr(s, rp + 1)
        }
        return s
    }

    /^[[:space:]]*```/            { fence = !fence; next }   # fence markers themselves go
    fence                         { print "    " $0; next }  # contents kept, indented, verbatim

    /^[[:space:]]*!\[[^]]*\]\([^)]*\)[[:space:]]*$/ { next }         # image lines
    /^[[:space:]]*<a id=/                           { next }         # HTML anchors
    /^>[[:space:]]*Part of the \[Plexus design set\]/ { next }       # repeated nav blockquote
    /^[[:space:]]*---[[:space:]]*$/                 { next }         # horizontal rules
    /^[[:space:]|:-]+$/ { if (index($0, "|") > 0 && index($0, "-") > 0) next }  # table rules

    {
        line = delink($0)
        gsub(/\\\|/, "\001", line)                # protect escaped pipes: |orbit| is notation,
        gsub(/&nbsp;/, " ", line)                 # not a table delimiter
        sub(/^#+[[:space:]]*/, "", line)          # heading markers
        sub(/^>[[:space:]]?/, "", line)           # blockquote marker
        gsub(/\*/, "", line)                      # emphasis
        gsub(/`/, "", line)                       # inline code
        sub(/^[[:space:]]*\|/, "", line)          # leading table pipe
        sub(/\|[[:space:]]*$/, "", line)          # trailing table pipe
        gsub(/[[:space:]]*\|[[:space:]]*/, "  ", line)   # interior pipes become spacing
        gsub(/\001/, "|", line)                   # restore the protected notation
        print line
    }
' > "$OUT.tmp"

# collapse runs of blank lines to a single blank line
awk 'NF==0 { b++; if (b<=1) print; next } { b=0; print }' "$OUT.tmp" > "$OUT"
rm -f "$OUT.tmp"
echo "wrote $OUT"
